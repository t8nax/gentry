// oldTools are the names of the tools before the scheme gentry <object>
// [<part>] <verb>: the texts name none of them.
var oldTools = []string{"stage_show", "stage_exit", "stage_skip", "step_add", "step_done", "step_drop", "note_add",
	"note_list", "artifact_save", "operator_record", "task_attempts", "library_diff", "library_apply", "library_discard",
	"process_status", "process_remote", "agents_sync"}

// TestNoOldNames checks that the skills and the guide name the tools by the
// commands, the subagents of the flow as those of the project and shared
// ones, and flow_show with no field active.
func TestNoOldNames(t *testing.T) {
	texts := map[string]string{"guide": FlowGuide()}
	for _, name := range []string{WorkingOnTask, CancelingTask, EditingFlow} {
		texts[name] = Skill(name)
	}
	for name, text := range texts {
		for _, tool := range oldTools {
			if regexp.MustCompile(`(^|[^A-Za-z0-9_])` + tool + `($|[^A-Za-z0-9_])`).MatchString(text) {
				t.Errorf("%s names the tool %s", name, tool)
			}
		}
		if strings.Contains(strings.ToLower(text), "библиот") {
			t.Errorf("%s names a library of subagents, not the shared subagents", name)
		}
		if regexp.MustCompile(`(?i)\bactive\b`).MatchString(text) {
			t.Errorf("%s names the field active", name)
		}
	}
}

